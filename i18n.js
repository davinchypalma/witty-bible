let lang = 'en';
export function setLang(l) { lang = l === 'fr' ? 'fr' : 'en'; }
export function getLang() { return lang; }
// a string in a given language (the themes follow the Bible's language)
export function tIn(l, key, vars) {
  const keep = lang;
  lang = l === 'fr' ? 'fr' : 'en';
  try { return t(key, vars); } finally { lang = keep; }
}
export function t(key, vars) {
  let s = TEXT[lang][key];
  if (s === undefined) s = TEXT.en[key];
  if (typeof s !== 'string') return s;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : ''));
  return s;
}
